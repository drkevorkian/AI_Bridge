import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const {UPDATE_PHASE,classifyBoundary,createCheckpoint,transitionCheckpoint,reviseCheckpoint,blocksDispatch,buildMatches}=require('../update_system/update-checkpoint.js');
const committed={dispatchId:'d1',status:'RESPONSE_COMMITTED'};
assert.equal(classifyBoundary({ledgerRecords:[committed]}).safe,true);
assert.equal(classifyBoundary({ledgerRecords:[{dispatchId:'d2',status:'AWAITING_RESPONSE'}]}).draining,true);
assert.equal(classifyBoundary({ledgerRecords:[{dispatchId:'d3',status:'DELIVERY_AMBIGUOUS'}]}).code,'DELIVERY_AMBIGUOUS');
assert.equal(classifyBoundary({parkedRecords:[{dispatchId:'d4',state:'CLAIMED'}]}).code,'RESPONSE_COMMIT_IN_PROGRESS');
assert.equal(classifyBoundary({providerRecovery:{active:true}}).code,'PROVIDER_RECOVERY_ACTIVE');
let cp=createCheckpoint({checkpointId:'cp',targetVersion:'1.2.0',targetBuild:'1.2.0.01-AI-B',currentVersion:'1.1.0',currentBuild:'1.1.0.99-AI-A',sessionActive:true,resumeRequested:true,nextTurnPending:{sourceDispatchId:'d1'},bindings:[{side:'A',tabId:1,provider:'chatgpt',documentId:'doc',generationEpoch:4,identity:{provider:'chatgpt',kind:'conversation',routeClass:'conversation',threadKey:'x',provisional:false,writable:true}}],createdAt:1});
assert.equal(blocksDispatch(cp),true);
cp=transitionCheckpoint(cp,UPDATE_PHASE.CHECKPOINTED,{},2);
cp=transitionCheckpoint(cp,UPDATE_PHASE.APPLIED_NOT_RELOADED,{},3);
cp=reviseCheckpoint(cp,{reloadAttempts:1},4);assert.equal(cp.reloadAttempts,1);
cp=transitionCheckpoint(cp,UPDATE_PHASE.RELOADED_NOT_REBOUND,{},5);
cp=transitionCheckpoint(cp,UPDATE_PHASE.READY_TO_RESUME,{},6);
cp=transitionCheckpoint(cp,UPDATE_PHASE.COMPLETE,{},7);
assert.equal(blocksDispatch(cp),false);
assert.equal(buildMatches(cp,{version:'1.2.0',build:'1.2.0.01-AI-B'}),true);
assert.throws(()=>transitionCheckpoint(cp,UPDATE_PHASE.RELOADED_NOT_REBOUND,{},8));
console.log('update-checkpoint-crash-stages: PASS');
