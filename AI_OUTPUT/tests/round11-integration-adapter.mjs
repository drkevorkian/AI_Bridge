import assert from 'node:assert/strict';
import {IntegrationStateAdapter,ACTION_CERTAINTY} from '../integration/integration-state-adapter.js';
import {HEALTH_CONTEXT,PROVIDER_STATUS} from '../integration/provider-health-reducer.js';
import {PAUSE_REASON,mapSubsystemReason} from '../integration/pause-reasons.js';
const a=new IntegrationStateAdapter();
assert.equal(mapSubsystemReason('STORE_FULL'),PAUSE_REASON.ROLLOVER_STORE_FULL);
assert.equal(mapSubsystemReason('STORE_TOTAL_BYTES_EXCEEDED'),PAUSE_REASON.ROLLOVER_STORE_CAPACITY_EXCEEDED);
assert.equal(mapSubsystemReason('PAYLOAD_TOO_LARGE'),PAUSE_REASON.ROLLOVER_RESPONSE_TOO_LARGE);
assert.equal(mapSubsystemReason('LEDGER_UNAVAILABLE'),PAUSE_REASON.ROLLOVER_LEDGER_UNAVAILABLE);
assert.equal(mapSubsystemReason('DISPATCH_MISSING'),PAUSE_REASON.ROLLOVER_DISPATCH_UNVERIFIED);
assert.equal(mapSubsystemReason('CLAIM_OUTCOME_AMBIGUOUS'),PAUSE_REASON.ROLLOVER_CLAIM_AMBIGUOUS);
const pause=a.pauseFromSubsystem({reason:'CLAIM_OUTCOME_AMBIGUOUS',side:'B',provider:'ChatGPT'});
assert.equal(pause.pause.certainty,ACTION_CERTAINTY.ACTION_OUTCOME_AMBIGUOUS);
assert.match(pause.pauseReason,/will not replay automatically/);
const dom=a.pauseFromDomCapability({capability:'send',authorityReason:'NO_TRUSTED_AUTHORITY',side:'A',provider:'ChatGPT'});
assert.equal(dom.pause.code,PAUSE_REASON.DOM_SEND_UNAVAILABLE);assert.equal(dom.pause.certainty,ACTION_CERTAINTY.NO_ACTION_TAKEN);
const pass={state:'PASS'},unsupported={state:'UNSUPPORTED'},fail={state:'FAIL'};
const base={composer:pass,send:pass,response:pass,conversation_identity:pass,limit_state:pass,new_chat:unsupported,upload:unsupported,stop:pass};
let h=a.providerHealth({provider:'chatgpt',bridgeConnected:true,capabilities:base,context:HEALTH_CONTEXT.RELAY});
assert.equal(h.status,PROVIDER_STATUS.DEGRADED);assert.equal(h.runnable,true);
h=a.providerHealth({provider:'chatgpt',bridgeConnected:true,capabilities:base,context:HEALTH_CONTEXT.ROLLOVER});
assert.equal(h.status,PROVIDER_STATUS.LIMITED);assert.equal(h.runnable,false);
h=a.providerHealth({provider:'chatgpt',bridgeConnected:true,capabilities:{...base,new_chat:pass},context:HEALTH_CONTEXT.ROLLOVER});
assert.equal(h.status,PROVIDER_STATUS.DEGRADED);assert.equal(h.runnable,true);
h=a.providerHealth({provider:'chatgpt',bridgeConnected:true,capabilities:{...base,send:fail},context:HEALTH_CONTEXT.RELAY});
assert.equal(h.status,PROVIDER_STATUS.BROKEN);assert.equal(h.runnable,false);
h=a.providerHealth({provider:'chatgpt',bridgeConnected:true,capabilities:base,context:HEALTH_CONTEXT.ARTIFACT_RELAY});
assert.equal(h.status,PROVIDER_STATUS.LIMITED);assert.equal(h.runnable,false);
h=a.providerHealth({provider:'chatgpt',bridgeConnected:false,capabilities:base,context:HEALTH_CONTEXT.RELAY});
assert.equal(h.status,PROVIDER_STATUS.DISCONNECTED);assert.equal(h.runnable,false);
console.log('round11-integration-adapter: PASS');
