import assert from 'node:assert/strict';
import {IntegrationStateAdapter,ACTION_CERTAINTY} from '../integration/integration-state-adapter.js';
import {PAUSE_REASON,mapSubsystemReason,pauseMeta} from '../integration/pause-reasons.js';
import {applyStructuredPause,clearStructuredPause,migrateLegacyPauseState,sanitizePause} from '../integration/pause-state-schema.js';
const a=new IntegrationStateAdapter();
assert.equal(mapSubsystemReason('NO_TRUSTED_AUTHORITY'),null);
const dom=a.pauseFromDomCapability({capability:'send',authorityReason:'NO_TRUSTED_AUTHORITY',side:'A',provider:'ChatGPT'});
assert.equal(dom.pause.code,PAUSE_REASON.DOM_SEND_UNAVAILABLE);
assert.equal(dom.pause.certainty,ACTION_CERTAINTY.NO_ACTION_TAKEN);
const disagree=a.pauseFromDomCapability({capability:'send',authorityReason:'CONTRACT_DISAGREEMENT',side:'A',provider:'ChatGPT'});
assert.equal(disagree.pause.code,PAUSE_REASON.DOM_CONTRACT_DISAGREEMENT);
const unknown=a.pauseFromSubsystem({reason:'FUTURE_NEW_REASON',side:'B',provider:'ChatGPT'});
assert.equal(unknown.pause.code,PAUSE_REASON.RUNTIME_UNMAPPED_SAFETY_STATE);
assert.equal(unknown.pause.certainty,ACTION_CERTAINTY.UNKNOWN);
assert.match(unknown.pause.detail,/FUTURE_NEW_REASON/);
assert.equal(pauseMeta('SOMETHING_NEW').certainty,ACTION_CERTAINTY.UNKNOWN);
const reconnect=a.pauseFromReconnectFailure({detail:'listener missing'});
assert.equal(reconnect.pause.code,PAUSE_REASON.RUNTIME_RECONNECT_FAILED);
assert.equal(reconnect.pause.certainty,ACTION_CERTAINTY.NO_ACTION_TAKEN);
let state={sessionActive:true,running:true,paused:false,pause:null,pauseReason:''};
state=applyStructuredPause(state,reconnect.pause);
assert.equal(state.running,false);assert.equal(state.paused,true);assert.ok(state.pause);assert.match(state.pauseReason,/could not reconnect/);
state=clearStructuredPause(state);assert.equal(state.paused,false);assert.equal(state.pause,null);assert.equal(state.pauseReason,'');
const legacy=migrateLegacyPauseState({running:false,paused:true,pauseReason:'Automatic reconnect failed: old prose'});
assert.equal(legacy.pause.code,PAUSE_REASON.RUNTIME_RECOVERY_FAILED);assert.equal(legacy.pause.certainty,ACTION_CERTAINTY.UNKNOWN);assert.match(legacy.pause.detail,/old prose/);
const corrupted=sanitizePause({code:'FUTURE_CODE',side:'b',provider:'X',certainty:'BOGUS',message:'x'});
assert.equal(corrupted.code,PAUSE_REASON.RUNTIME_UNMAPPED_SAFETY_STATE);assert.equal(corrupted.certainty,ACTION_CERTAINTY.UNKNOWN);assert.equal(corrupted.sourceCode,'FUTURE_CODE');
console.log('round12-pause-state: PASS');
