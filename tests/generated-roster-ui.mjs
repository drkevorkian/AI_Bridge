import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const html = fs.readFileSync(path.join(root, "dashboard.html"), "utf8");
const prelude = fs.readFileSync(path.join(root, "dashboard-roster-prelude.js"), "utf8");
const dynamic = fs.readFileSync(path.join(root, "dashboard-dynamic-agents.js"), "utf8");

assert.match(html, /id="agentRosterHost"/);
assert.doesNotMatch(html, /<article class="agent-card agent-[a-e]"/i,
  "agent cards must be generated, not hardcoded in dashboard.html");
for (const id of ["tabA", "tabB", "tabC", "jobA", "jobB", "jobC", "forceFromA", "forceToA"]) {
  assert.doesNotMatch(html, new RegExp(`id="${id}"`),
    `${id} must be generated by the roster prelude`);
}

const preludeIndex = html.indexOf('<script src="dashboard-roster-prelude.js"></script>');
const dashboardIndex = html.indexOf('<script src="dashboard.js"></script>');
assert.ok(preludeIndex >= 0 && preludeIndex < dashboardIndex,
  "generated roster must exist before dashboard.js binds legacy handlers");

assert.match(prelude, /MAX_COMPAT_AGENTS = 5/);
assert.match(prelude, /for \(let ordinal = 1; ordinal <= MAX_COMPAT_AGENTS; ordinal \+= 1\)/);
assert.match(prelude, /dataset\.agentId = agentIdForOrdinal\(ordinal\)/);
assert.match(prelude, /dataset\.ordinal = String\(ordinal\)/);
assert.match(prelude, /setAttribute\("role", "listitem"\)/);
assert.match(prelude, /replaceChildren\(\)/);
assert.doesNotMatch(prelude, /innerHTML|insertAdjacentHTML|document\.write|eval\s*\(|new Function/,
  "generated roster must use safe DOM construction only");

assert.match(dynamic, /__AI_BRIDGE_ROSTER_UI_PRELUDE_V1__/);
assert.match(dynamic, /generatedRosterUi:\s*true/);
assert.match(dynamic, /canonicalAgentMetadata:\s*true/);
assert.doesNotMatch(dynamic, /function createExtendedCard\(/,
  "dynamic adapter must not maintain a second card construction path");
assert.match(dynamic, /Generated roster identity mismatch/);
assert.match(dynamic, /const forceFrom = byId\(`forceFrom\$\{side\}`\)/);
assert.match(dynamic, /forceFrom\.addEventListener\("click", \(\) => \{/);
assert.match(dynamic, /setForceSource\(side\)/,
  "generated D/E manual-source controls must select their own source");

console.log("generated-roster-ui: pre-dashboard canonical roster generation ok");
